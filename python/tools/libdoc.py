"""Purpose: generate website/reference/metta-libraries.md from the
`(@doc ...)` atoms the MeTTa libraries carry, the same
true-by-construction promise reference.py makes for the Python modules:
both languages' docs come from their own sources through one pipeline.
The coverage table is the burn-down surface, interrogate's role for the
MeTTa side: a library gains entries here by gaining @doc atoms.

Assumes:
  - the engine's own reader parses every lib/lib_*.metta; forms are READ
    and never run, so a library needing an absent backend still documents
    [tested test_the_metta_library_page_is_up_to_date]
Guarantees:
  - the checked-in page equals what this produces, gated on every run
    [tested test_the_metta_library_page_is_up_to_date]
Fails when:
  - a library defines names only through runnable `!(...)` side effects;
    the static reading cannot see those, so they go uncounted
Open Obligations:
  To Do: None
  Hacks: None
  Future Enhancements: None
"""

from __future__ import annotations

import pathlib
import sys

_REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO / "python"))

from petta import Expr, Gnd, Sym, parse  # noqa: E402
from petta._source_forms import positioned_forms  # noqa: E402

_PAGE = _REPO / "website" / "reference" / "metta-libraries.md"

_PREAMBLE = """# The MeTTa libraries

`!(import! &self (library lib_x))` loads one. The entries below reproduce
each library's own `(@doc ...)` atoms, generated by
`python/tools/libdoc.py`, so they are true by construction; `help!` and
`get-doc` answer the same atoms live. The coverage table is the
burn-down surface: a library appears below it by gaining `@doc` atoms
beside its definitions."""


def _forms(source: str) -> list[tuple]:
    """Every form in the source with its line, read and never run: the
    engine door the boot manifest reads through, which is what lets a
    library whose backend is absent still document itself."""
    return [
        (parse(form.text), form.line)
        for form in positioned_forms(source)
        if form.kind != "runnable"
    ]


def _named(atom) -> str | None:
    """The name a (= ...) or (: ...) form defines or declares."""
    if not isinstance(atom, Expr) or len(atom.children) < 3:
        return None
    head, subject = atom.children[0], atom.children[1]
    if head == Sym("="):
        if isinstance(subject, Expr) and subject.children and isinstance(subject.children[0], Sym):
            return subject.children[0].name
        if isinstance(subject, Sym):
            return subject.name
    if head == Sym(":") and isinstance(subject, Sym):
        return subject.name
    return None


def _text(atom) -> str:
    """The prose inside a doc part: a string value decodes, anything else
    renders as written."""
    if isinstance(atom, Gnd) and isinstance(atom.value, str):
        return atom.value
    return str(atom)


def _entry(doc: Expr, declared: dict[str, str], where: str) -> list[str]:
    """One @doc atom as markdown: heading, source line, declared type,
    description, parameters, and return, parts absent when unwritten."""
    name = doc.children[1]
    lines = [f"### `{name}`", "", f"*{where}*", ""]
    if str(name) in declared:
        lines += [f"```metta\n(: {name} {declared[str(name)]})\n```", ""]
    for part in doc.children[2:]:
        if not (isinstance(part, Expr) and part.children):
            continue
        head, *rest = part.children
        if head == Sym("@desc") and rest:
            lines += [_text(rest[0]), ""]
        elif head == Sym("@params") and rest and isinstance(rest[0], Expr):
            for position, parameter in enumerate(rest[0].children, start=1):
                detail = parameter.children[1] if (
                    isinstance(parameter, Expr) and len(parameter.children) > 1
                ) else parameter
                lines.append(f"{position}. {_text(detail)}")
            lines.append("")
        elif head == Sym("@return") and rest:
            lines += [f"Returns: {_text(rest[0])}", ""]
    return lines


def _library(path: pathlib.Path) -> tuple[str, int, int, list[str]]:
    """One library's coverage numbers and rendered section."""
    forms = _forms(path.read_text(encoding="utf-8"))
    docs = [
        (f, line)
        for f, line in forms
        if isinstance(f, Expr) and f.children and f.children[0] == Sym("@doc")
    ]
    declared = {
        str(f.children[1]): str(f.children[2])
        for f, _line in forms
        if isinstance(f, Expr) and len(f.children) == 3 and f.children[0] == Sym(":")
        and isinstance(f.children[1], Sym)
    }
    names = {name for form, _line in forms if (name := _named(form)) is not None}
    documented = {str(d.children[1]) for d, _line in docs if len(d.children) > 1}
    section: list[str] = []
    if docs:
        section = [f"## {path.stem}", ""]
        for doc, line in docs:
            section += _entry(doc, declared, f"{path.name}:{line}")
        missing = sorted(names - documented)
        if missing:
            section += [
                "Undocumented: " + ", ".join(f"`{name}`" for name in missing),
                "",
            ]
    return path.stem, len(names | documented), len(documented), section


def page() -> str:
    rows = [_library(path) for path in sorted((_REPO / "lib").glob("lib_*.metta"))]
    table = ["| library | names | documented |", "|---|---|---|"]
    table += [f"| {name} | {total} | {done} |" for name, total, done, _ in rows]
    body: list[str] = []
    for _name, _total, _done, section in rows:
        body += section
    return "\n".join([_PREAMBLE, "", *table, "", *body]).rstrip() + "\n"


def main(argv: list[str]) -> int:
    wanted = page()
    current = _PAGE.read_text(encoding="utf-8") if _PAGE.exists() else ""
    if current == wanted:
        return 0
    if "--write" in argv:
        _PAGE.write_text(wanted, encoding="utf-8")
        print(f"rewrote {_PAGE.name}")
        return 0
    print(
        f"{_PAGE.name} no longer matches the libraries' @doc atoms: "
        f"run python/tools/libdoc.py --write"
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
