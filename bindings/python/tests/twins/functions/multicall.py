def twin(m):
    """Two alternatives for one head, and the answers both of them give."""
    @m.define
    def mycalc(x, y):
        # (= (mycalc $x $y) (+ $x $y))
        yield x + y
        # (= (mycalc $x $y) (- $x $y))
        yield x - y

    assert mycalc(1, 2) == [3, -1]
